#!/usr/bin/python3
def add(a, b):
    """Return the sum of two integers."""
    return a + b


def sub(a, b):
    """Return the difference between two integers."""
    return a - b


def mul(a, b):
    """Return the product of two integers."""
    return a * b


def div(a, b):
    """Return the integer result of dividing a by b."""
    return int(a / b)
